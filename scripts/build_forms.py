"""Write the RA03-LITE Attributes_Form and the filled V1-V4 forms (Req 9.1, 9.5, 26.1).

Run from the repo root: ``uv run python scripts/build_forms.py``. Deterministic.
"""
from __future__ import annotations

import copy
import json
from pathlib import Path

import yaml

from calm_generation.attributes import form_for

ROOT = Path(__file__).resolve().parents[1]
TPL = ROOT / "calm-app-generation-framework" / "templates" / "RA03-LITE.json"
FORMS = ROOT / "governance-execution-framework" / "forms"

V1 = {  # compliant design
    "INVOICE_INTELLIGENCE_AGENT_AUTONOMY": "semi-autonomous",
    "PAYMENT_AGENT_AUTONOMY": "supervised",
    "PAYMENT_AGENT_PRIVILEGE": "restricted-write",
    "PAYMENT_AGENT_PAYMENT_APPROVAL_PATH": "via-human-approval",
    "PAYMENT_AGENT_PAYMENT_LIMIT": 25000,
    "FOUNDATION_MODEL_MODEL_VERSION": "pinned",
    "INVOICE_DB_DATA_CLASSIFICATION": "supplier-financial",   # outside the Taxonomy: stays UNMAPPED (Req 13.7)
}
OPTS_V1 = {"opt-approval-path": "payment-via-human-approval-service", "opt-audit": ["audit-service-present"]}

VARIANTS = {
    "v1": ("Invoice-Lite V1 (compliant)", V1, OPTS_V1),
    "v2": ("Invoice-Lite V2 (direct payment, unrestricted write)",
           {**V1, "PAYMENT_AGENT_PRIVILEGE": "unrestricted-write", "PAYMENT_AGENT_PAYMENT_APPROVAL_PATH": "direct"},
           {**OPTS_V1, "opt-approval-path": "direct-to-payment-api"}),
    "v3": ("Invoice-Lite V3 (no audit, autonomous payment agent)",
           {**V1, "PAYMENT_AGENT_AUTONOMY": "autonomous"},
           {**OPTS_V1, "opt-audit": ["no-audit-service"]}),
    "v4": ("Invoice-Lite V4 (invalid instance: payment limit above the pattern maximum)",
           {**V1, "PAYMENT_AGENT_PAYMENT_LIMIT": 250000}, OPTS_V1),
}


def main() -> None:
    """Write the base attribute form generated from the RA03-LITE template, plus one filled form per entry in VARIANTS."""
    text = TPL.read_text(encoding="utf-8")
    base = form_for(json.loads(text), text, "PUBLISHED")
    FORMS.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/build_forms.py from templates/RA03-LITE.json. Fill `app`, `values` and `options.selected`.\n"
    (FORMS / "ra03-lite.attributes.yaml").write_text(header + yaml.safe_dump(base, sort_keys=False), encoding="utf-8")
    names = {a["name"] for a in base["attributes"]}
    for vid, (title, values, opts) in VARIANTS.items():
        assert set(values) <= names, set(values) - names
        f = copy.deepcopy(base)
        f["app"] = {"id": f"invoice-lite-{vid}", "name": title}
        f["values"] = dict(sorted(values.items()))
        for o in f["options"]:
            o["selected"] = opts[o["unique_id"]]
        (FORMS / f"{vid}.attributes.yaml").write_text(f"# Variant {vid.upper()}: {title}\n" + yaml.safe_dump(f, sort_keys=False),
                                                      encoding="utf-8")
        print(vid, "written")


if __name__ == "__main__":
    main()
